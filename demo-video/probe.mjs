// Probe: can headless Chrome type into PayPal's card fields on a throwaway CardBuddy instance?
import { chromium } from 'playwright-core';
import { spawn } from 'node:child_process';
import fs from 'node:fs'; import os from 'node:os'; import path from 'node:path';
const APP = path.resolve('..'), PORT = 4400, data = fs.mkdtempSync(path.join(os.tmpdir(), 'cardbuddy-probe-'));
const srv = spawn(process.execPath, ['server.mjs'], { cwd: APP, env: { ...process.env, PORT: String(PORT), CARDBUDDY_DATA: data, GMAIL_USER: '', GMAIL_APP_PASSWORD: '' }, stdio: ['ignore', 'pipe', 'pipe'] });
srv.stdout.on('data', d => { if (/running at/.test(d)) console.log('server up'); }); srv.stderr.on('data', d => console.log('srv err', String(d).slice(0, 300)));
await new Promise(r => setTimeout(r, 1500));
process.on('unhandledRejection', e => { console.log('ERR', String(e.message).slice(0, 300)); process.exit(1); });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 1.5, userAgent: 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/141.0.0.0 Safari/537.36' });
const page = await ctx.newPage();
page.on('console', m => console.log('console', m.type(), m.text().slice(0, 200)));
await page.goto(`http://localhost:${PORT}/`);
await page.waitForSelector('#cardForm:not(.pp-wait)', { timeout: 30000 });
console.log('fields ready');
await page.selectOption('#which', 'double-cash');
const f = sel => page.frameLocator(sel + ' iframe.zoid-visible').locator('input');
await f('#name').pressSequentially('Alex Rivera', { delay: 40 });
await f('#number').pressSequentially('2223000048400011', { delay: 40 });
await f('#expiry').pressSequentially('1230', { delay: 40 });
await f('#cvv').pressSequentially('123', { delay: 40 });
await page.check('#makeDefault');
await page.screenshot({ path: path.join(os.tmpdir(), 'probe1.png') });
await page.click('#save');
await page.waitForFunction(() => /Saved|couldn|Check|PayPal/.test(document.getElementById('msg').textContent) && !/Sending|Saving/.test(document.getElementById('msg').textContent), null, { timeout: 40000 });
console.log('msg:', await page.textContent('#msg'));
await page.waitForTimeout(1500);
await page.screenshot({ path: path.join(os.tmpdir(), 'probe2.png') });
await browser.close(); srv.kill(); console.log('data', data);
